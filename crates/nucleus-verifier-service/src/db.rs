//! SQLite persistence layer for the verifier-service.
//!
//! Optional — when [`AppState::db`](crate::app::AppState) is `None`
//! the service runs in legacy stateless mode and no records are
//! written. When `Some(Db)`, every verification is recorded
//! and addressable by envelope hash via the
//! `GET /v1/bundles/{hash}/verify` endpoint (task #68 wires that).
//!
//! # Why SQLite (not Postgres) in v1
//!
//! - Fly.io single-volume deployment is the v1 ship target; SQLite
//!   removes one moving part vs. running a Postgres sidecar.
//! - All access is single-writer (verifier-service) + many-reader (the
//!   public verify endpoint); SQLite's WAL mode handles this well.
//! - Migrations are checked-in plain `.sql` files; no DB ops required.
//! - Multi-region read replicas can come later via litestream / LiteFS;
//!   no schema change needed to swap the storage substrate.
//!
//! # Driver
//!
//! `rusqlite` with its bundled SQLite. This crate used `sqlx` until
//! 2026-11; `sqlx-sqlite` 0.9.0 (the latest release) caps
//! `libsqlite3-sys` below 0.38, and every bundled SQLite before 3.54.0 is
//! affected by RUSTSEC-2026-0459 (uninitialized page-cache memory returned
//! when a database is opened with a `-wal` file of a different page size).
//!
//! One connection, behind a mutex, used from tokio's blocking pool. Every
//! statement here is a single-row read or write, so serialising them costs
//! little next to the Ed25519 work the verify path does per request.
//!
//! Migrations keep `sqlx`'s bookkeeping table (`_sqlx_migrations`, same
//! columns, same SHA-384 checksum of the script), so a database file written
//! by an earlier release opens without re-running a migration, and a script
//! edited after it was applied is refused rather than skipped.

use std::path::Path;
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use anyhow::{Context, Result, anyhow, bail};
use rusqlite::{Connection, OptionalExtension, params};
use sha2::{Digest, Sha384};

/// How long a statement waits on a lock held by another process (an
/// operator's `sqlite3` shell, a backup) before failing. `sqlx`'s default.
const BUSY_TIMEOUT: Duration = Duration::from_secs(5);

/// The bookkeeping table `sqlx::migrate!` created. Kept by name so that
/// databases migrated by earlier releases are recognised.
const MIGRATIONS_TABLE: &str = "_sqlx_migrations";

/// One embedded migration script, derived by `build.rs` from
/// `migrations/<version>_<description>.sql`.
struct Migration {
    version: i64,
    /// File-name description with `_` read as a space, as `sqlx` stored it.
    description: &'static str,
    sql: &'static str,
}

/// Every file in `migrations/`, in version order (generated by `build.rs`).
const MIGRATIONS: &[Migration] = include!(concat!(env!("OUT_DIR"), "/migrations.rs"));

/// Handle to the verification database. Cheap to clone: every clone shares
/// the one connection.
#[derive(Clone)]
pub struct Db {
    conn: Arc<Mutex<Connection>>,
}

impl Db {
    /// Run `f` against the connection on tokio's blocking pool.
    pub(crate) async fn call<T, F>(&self, f: F) -> Result<T>
    where
        T: Send + 'static,
        F: FnOnce(&mut Connection) -> Result<T> + Send + 'static,
    {
        let conn = Arc::clone(&self.conn);
        tokio::task::spawn_blocking(move || {
            // A poisoned lock means a statement panicked part-way; the
            // connection's state is unknown, so refuse rather than carry on.
            let mut guard = conn.lock().map_err(|_| {
                anyhow!("verifier database connection poisoned by an earlier panic")
            })?;
            f(&mut guard)
        })
        .await
        .context("verifier database task did not complete")?
    }
}

/// Where a `--db` value points.
#[derive(Debug, PartialEq, Eq)]
enum Location<'a> {
    Memory,
    File(&'a str),
}

/// Parse the accepted `--db` forms. Query parameters (`?mode=…`) were
/// accepted by `sqlx` and are refused here rather than becoming part of a
/// file name.
fn parse_location(db_url: &str) -> Result<Location<'_>> {
    let rest = db_url
        .strip_prefix("sqlite://")
        .or_else(|| db_url.strip_prefix("sqlite:"))
        .unwrap_or(db_url);
    if rest.contains('?') {
        bail!("database URL query parameters are not supported: {db_url}");
    }
    match rest {
        "" => bail!("database URL names no file: {db_url:?}"),
        ":memory:" => Ok(Location::Memory),
        path => Ok(Location::File(path)),
    }
}

/// Open the database, create the file if missing, enable WAL for
/// many-reader/single-writer concurrency, and run embedded migrations.
///
/// `db_url` accepts:
/// - `sqlite::memory:` (tests)
/// - `sqlite:/data/verifier.db` (Fly.io volume mount)
/// - any path-shaped string is treated as `sqlite:<path>`
pub async fn connect_and_migrate(db_url: &str) -> Result<Db> {
    let (conn, journal) = match parse_location(db_url)? {
        Location::Memory => (Connection::open_in_memory(), "memory"),
        // Opens read-write and creates the file on first connect, so the
        // Fly.io initial deploy needs no bootstrap step.
        Location::File(path) => (Connection::open(path), "wal"),
    };
    let conn = conn.with_context(|| format!("opening sqlite database {db_url}"))?;
    let conn = tokio::task::spawn_blocking(move || configure_and_migrate(conn, journal))
        .await
        .context("verifier database migration task did not complete")??;
    Ok(Db {
        conn: Arc::new(Mutex::new(conn)),
    })
}

/// `expected_journal` is what SQLite reports after `journal_mode=WAL`:
/// `wal` for a file, `memory` for an in-memory database, which has no file
/// to log beside.
fn configure_and_migrate(mut conn: Connection, expected_journal: &str) -> Result<Connection> {
    conn.busy_timeout(BUSY_TIMEOUT)
        .context("setting busy_timeout")?;
    // `log_entries.envelope_hash` references `verifications`; SQLite leaves
    // foreign keys unenforced unless asked, and `sqlx` asked by default.
    conn.pragma_update(None, "foreign_keys", true)
        .context("enabling foreign_keys")?;
    // WAL = readers don't block the writer.
    let mode: String = conn
        .pragma_update_and_check(None, "journal_mode", "WAL", |row| row.get(0))
        .context("setting journal_mode=WAL")?;
    if !mode.eq_ignore_ascii_case(expected_journal) {
        bail!("journal_mode is {mode:?}, expected {expected_journal:?}");
    }
    // NORMAL synchronous is the WAL-mode-recommended setting — FULL is
    // overkill (no extra durability over WAL checkpoints) and OFF risks
    // corruption on power loss.
    conn.pragma_update(None, "synchronous", "NORMAL")
        .context("setting synchronous=NORMAL")?;
    migrate(&mut conn).context("running embedded migrations failed")?;
    Ok(conn)
}

/// Apply every embedded migration not yet recorded, refusing a database
/// whose record disagrees with the embedded scripts.
fn migrate(conn: &mut Connection) -> Result<()> {
    conn.execute_batch(&format!(
        "CREATE TABLE IF NOT EXISTS {MIGRATIONS_TABLE} (
            version BIGINT PRIMARY KEY,
            description TEXT NOT NULL,
            installed_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            success BOOLEAN NOT NULL,
            checksum BLOB NOT NULL,
            execution_time BIGINT NOT NULL
        );"
    ))?;

    let applied: Vec<(i64, bool, Vec<u8>)> = {
        let mut stmt = conn.prepare(&format!(
            "SELECT version, success, checksum FROM {MIGRATIONS_TABLE} ORDER BY version"
        ))?;
        stmt.query_map([], |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)))?
            .collect::<rusqlite::Result<_>>()?
    };

    for (version, success, checksum) in &applied {
        if !success {
            bail!("migration {version} is recorded as partially applied (dirty database)");
        }
        let Some(migration) = MIGRATIONS.iter().find(|m| m.version == *version) else {
            bail!(
                "migration {version} was applied to this database but is not embedded in this build"
            );
        };
        if Sha384::digest(migration.sql).as_slice() != checksum.as_slice() {
            bail!("migration {version} was edited after it was applied (checksum mismatch)");
        }
    }

    for migration in MIGRATIONS {
        if applied
            .iter()
            .any(|(version, _, _)| *version == migration.version)
        {
            continue;
        }
        let start = Instant::now();
        let tx = conn.transaction()?;
        tx.execute_batch(migration.sql).with_context(|| {
            format!(
                "migration {} ({})",
                migration.version, migration.description
            )
        })?;
        tx.execute(
            &format!(
                "INSERT INTO {MIGRATIONS_TABLE} (version, description, success, checksum, execution_time) \
                 VALUES (?1, ?2, TRUE, ?3, -1)"
            ),
            params![
                migration.version,
                migration.description,
                Sha384::digest(migration.sql).to_vec()
            ],
        )?;
        tx.commit()?;
        let nanos = i64::try_from(start.elapsed().as_nanos()).unwrap_or(i64::MAX);
        conn.execute(
            &format!("UPDATE {MIGRATIONS_TABLE} SET execution_time = ?1 WHERE version = ?2"),
            params![nanos, migration.version],
        )?;
    }
    Ok(())
}

/// Helper variant for tests/CI that takes a raw path.
pub async fn connect_and_migrate_path(path: &Path) -> Result<Db> {
    let url = format!("sqlite:{}", path.display());
    connect_and_migrate(&url).await
}

/// A persisted verification record. Mirrors the `verifications` table.
#[derive(Debug, Clone, PartialEq)]
pub struct VerificationRecord {
    /// SHA-256 hex of `nucleus_envelope::canonical_bundle_hash`
    /// — primary key + URL component for the lookup endpoint.
    pub envelope_hash: String,
    /// Unix seconds at submission.
    pub submitted_at: i64,
    /// Size of the bundle JSON the verifier received (for telemetry
    /// + retention sweeper budget).
    pub payload_size_bytes: i64,
    /// `true` when verification succeeded; `false` on any failure.
    pub ok: bool,
    /// Discriminant of `VerifyBundleError` when `!ok`. Stable across
    /// release versions of `nucleus-envelope`.
    pub error_kind: Option<String>,
    /// Full `VerificationReport` JSON on success; `None` on failure.
    pub report_json: Option<String>,
}

/// Idempotent insert. Re-submitting the same `envelope_hash` is a
/// no-op (we treat it as "we already verified that bundle"; the
/// stored report wins).
pub async fn record_verification(db: &Db, rec: &VerificationRecord) -> Result<()> {
    let rec = rec.clone();
    db.call(move |conn| {
        conn.execute(
            "INSERT INTO verifications \
                (envelope_hash, submitted_at, payload_size_bytes, ok, error_kind, report_json) \
             VALUES (?1, ?2, ?3, ?4, ?5, ?6) \
             ON CONFLICT(envelope_hash) DO NOTHING",
            params![
                rec.envelope_hash,
                rec.submitted_at,
                rec.payload_size_bytes,
                if rec.ok { 1i64 } else { 0i64 },
                rec.error_kind,
                rec.report_json,
            ],
        )
        .context("INSERT INTO verifications failed")?;
        Ok(())
    })
    .await
}

/// Look up a previously-recorded verification by envelope hash.
pub async fn fetch_verification(
    db: &Db,
    envelope_hash: &str,
) -> Result<Option<VerificationRecord>> {
    let envelope_hash = envelope_hash.to_string();
    db.call(move |conn| {
        conn.query_row(
            "SELECT envelope_hash, submitted_at, payload_size_bytes, ok, error_kind, report_json \
             FROM verifications WHERE envelope_hash = ?1",
            params![envelope_hash],
            |r| {
                Ok(VerificationRecord {
                    envelope_hash: r.get(0)?,
                    submitted_at: r.get(1)?,
                    payload_size_bytes: r.get(2)?,
                    ok: r.get::<_, i64>(3)? != 0,
                    error_kind: r.get(4)?,
                    report_json: r.get(5)?,
                })
            },
        )
        .optional()
        .context("SELECT FROM verifications failed")
    })
    .await
}

#[cfg(test)]
mod tests {
    use super::*;

    async fn fresh_pool() -> Db {
        // Each in-memory test gets its own DB to avoid cross-test bleed.
        connect_and_migrate("sqlite::memory:").await.unwrap()
    }

    async fn count(db: &Db, sql: &'static str) -> i64 {
        db.call(move |conn| Ok(conn.query_row(sql, [], |r| r.get(0))?))
            .await
            .unwrap()
    }

    #[test]
    fn accepted_url_forms_parse() {
        assert_eq!(parse_location("sqlite::memory:").unwrap(), Location::Memory);
        assert_eq!(
            parse_location("sqlite:/data/verifier.db").unwrap(),
            Location::File("/data/verifier.db")
        );
        assert_eq!(
            parse_location("sqlite://data.db").unwrap(),
            Location::File("data.db")
        );
        assert_eq!(
            parse_location("/data/verifier.db").unwrap(),
            Location::File("/data/verifier.db")
        );
        assert!(parse_location("sqlite:/data/verifier.db?mode=ro").is_err());
        assert!(parse_location("sqlite:").is_err());
    }

    #[test]
    fn every_migration_file_is_embedded_in_order() {
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("migrations");
        let mut files: Vec<String> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|e| e.unwrap().file_name().into_string().unwrap())
            .collect();
        files.sort();
        assert!(
            !files.is_empty(),
            "no migrations found in {}",
            dir.display()
        );
        assert_eq!(files.len(), MIGRATIONS.len());
        for (file, m) in files.iter().zip(MIGRATIONS) {
            let expected = format!("{}_{}.sql", m.version, m.description.replace(' ', "_"));
            assert_eq!(file, &expected);
        }
    }

    #[tokio::test]
    async fn migrations_run_on_fresh_db() {
        let pool = fresh_pool().await;
        // Schema migration created the table; a select on it must
        // succeed (even with zero rows).
        assert_eq!(count(&pool, "SELECT COUNT(*) FROM verifications").await, 0);
        assert_eq!(
            count(&pool, "SELECT COUNT(*) FROM _sqlx_migrations WHERE success").await,
            MIGRATIONS.len() as i64
        );
    }

    #[tokio::test]
    async fn reopening_a_file_database_keeps_rows_and_applies_nothing_twice() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("verifier.db");
        let rec = VerificationRecord {
            envelope_hash: "e".repeat(64),
            submitted_at: 1,
            payload_size_bytes: 1,
            ok: true,
            error_kind: None,
            report_json: None,
        };
        {
            let db = connect_and_migrate_path(&path).await.unwrap();
            record_verification(&db, &rec).await.unwrap();
        }
        let db = connect_and_migrate_path(&path).await.unwrap();
        assert_eq!(
            fetch_verification(&db, &rec.envelope_hash).await.unwrap(),
            Some(rec)
        );
        assert_eq!(
            count(&db, "SELECT COUNT(*) FROM _sqlx_migrations").await,
            MIGRATIONS.len() as i64
        );
    }

    #[tokio::test]
    async fn an_edited_migration_is_refused() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("verifier.db");
        let db = connect_and_migrate_path(&path).await.unwrap();
        db.call(|conn| {
            conn.execute(
                "UPDATE _sqlx_migrations SET checksum = x'00' WHERE version = (SELECT MIN(version) FROM _sqlx_migrations)",
                [],
            )?;
            Ok(())
        })
        .await
        .unwrap();
        drop(db);
        let err = connect_and_migrate_path(&path)
            .await
            .err()
            .expect("refused");
        assert!(format!("{err:#}").contains("checksum mismatch"), "{err:#}");
    }

    #[tokio::test]
    async fn round_trip_success_record() {
        let pool = fresh_pool().await;
        let rec = VerificationRecord {
            envelope_hash: "a".repeat(64),
            submitted_at: 1_700_000_000,
            payload_size_bytes: 4096,
            ok: true,
            error_kind: None,
            report_json: Some(r#"{"trust_mode":"jwks","edge_count":3}"#.to_string()),
        };
        record_verification(&pool, &rec).await.unwrap();
        let back = fetch_verification(&pool, &rec.envelope_hash)
            .await
            .unwrap()
            .expect("just inserted");
        assert_eq!(back, rec);
    }

    #[tokio::test]
    async fn round_trip_failure_record() {
        let pool = fresh_pool().await;
        let rec = VerificationRecord {
            envelope_hash: "b".repeat(64),
            submitted_at: 1_700_000_001,
            payload_size_bytes: 512,
            ok: false,
            error_kind: Some("BadSignature".to_string()),
            report_json: None,
        };
        record_verification(&pool, &rec).await.unwrap();
        let back = fetch_verification(&pool, &rec.envelope_hash)
            .await
            .unwrap()
            .unwrap();
        assert!(!back.ok);
        assert_eq!(back.error_kind.as_deref(), Some("BadSignature"));
        assert!(back.report_json.is_none());
    }

    #[tokio::test]
    async fn fetch_returns_none_for_unknown_hash() {
        let pool = fresh_pool().await;
        let got = fetch_verification(&pool, &"c".repeat(64)).await.unwrap();
        assert!(got.is_none());
    }

    #[tokio::test]
    async fn idempotent_insert_does_not_overwrite() {
        let pool = fresh_pool().await;
        let r1 = VerificationRecord {
            envelope_hash: "d".repeat(64),
            submitted_at: 1,
            payload_size_bytes: 100,
            ok: true,
            error_kind: None,
            report_json: Some("first".to_string()),
        };
        let r2 = VerificationRecord {
            envelope_hash: "d".repeat(64), // same hash
            submitted_at: 2,
            payload_size_bytes: 200,
            ok: false,
            error_kind: Some("ShouldNotOverwrite".to_string()),
            report_json: Some("second".to_string()),
        };
        record_verification(&pool, &r1).await.unwrap();
        record_verification(&pool, &r2).await.unwrap();
        let back = fetch_verification(&pool, &r1.envelope_hash)
            .await
            .unwrap()
            .unwrap();
        // First-write-wins: r2's fields must NOT overwrite r1's.
        assert_eq!(back, r1);
    }
}

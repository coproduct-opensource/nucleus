//! `cargo xtask live-boot-evidence` — turn a CI live boot into a verified
//! evidence bundle.
//!
//! On a KVM host after `nucleus setup`:
//!
//! 1. **Collect.** The `nucleus-cli` live collector boots a fresh,
//!    host-spec-enforcing node from the installed binary and runs two pods: the
//!    posture workload (the in-guest probes), which yields the admission, the
//!    signed execution receipt, the exact logs and a declared artifact; and one
//!    credentialed request, which yields the host-effect journal. It also
//!    measures the node binaries as they ran, the platform the receipt states,
//!    and timings. It verifies nothing.
//! 2. **Predict.** The reference manifest a release of this build would publish
//!    is generated by the release's own function and its predictions are
//!    checked against what booted.
//! 3. **Verify, publicly.** `nucleus-audit` (prepare-execution, then
//!    verify-execution, verify-logs, verify-artifacts, verify-host-effects, and
//!    verify-node-evidence when the receipt names evidence), the JS SDK and the
//!    Python SDK judge the same inputs and must agree. Each verifier is also
//!    handed a tampered input it must refuse.
//! 4. **Write** the bundle directory and `summary.json`, and exit non-zero on
//!    any failure. Every check is `pass | fail | could_not_run`, and
//!    `could_not_run` is red unless `--allow-could-not-run` names it.
//!
//! An unattested node is recorded as `unattested` with the receipt's reason.
//! Nothing here upgrades it.


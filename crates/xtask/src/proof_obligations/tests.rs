/// The one row, checked against the fixture: its violations.
fn violations_of(row: &str) -> Vec<String> {
    let dir = fixture();
    let (_, _, errors) = violations(dir.path(), row).unwrap();
    errors
}

/// Red, exactly once, and for the reason named — not for some other refusal.
fn red_for(row: &str, reason: &str) {
    let errors = violations_of(row);
    assert_eq!(
        errors.len(),
        1,
        "expected exactly one violation, got {errors:#?}"
    );
    assert!(
        errors[0].contains(reason),
        "red for the wrong reason: {errors:#?}"
    );
}


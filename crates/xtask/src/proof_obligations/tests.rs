const KANI_WORKFLOW: &str = "jobs:\n  kani:\n    steps:\n      - uses: model-checking/kani-github-action@pin\n        with:\n          args: >-\n            -p demo\n            --harness proof_admit\n            --harness proof_trivial\n            --harness proof_unrelated\n            --harness proof_never\n";

const LEAN_WORKFLOW: &str = "jobs:\n  lean:\n    steps:\n      - uses: leanprover/lean-action@pin\n        with:\n          build: 'true'\n          lake-package-directory: crates/demo/lean\n          build-args: Proofs\n";

const LAKEFILE: &str = "package «demo» where\n\nlean_lib «Gen» where\n  roots := #[`Demo.Funs]\n  srcDir := \"generated\"\n\nlean_lib «Proofs» where\n  roots := #[`Proofs]\n";

fn write(root: &Path, path: &str, text: &str) {
    let p = root.join(path);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, text).unwrap();
}

fn fixture() -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(
        root,
        "Cargo.toml",
        "[workspace]\nmembers = [\"crates/demo\"]\n",
    );
    write(
        root,
        "crates/demo/Cargo.toml",
        "[package]\nname = \"demo\"\n",
    );
    write(root, "crates/demo/src/lib.rs", &lib());
    write(root, ".github/workflows/kani.yml", KANI_WORKFLOW);
    write(root, ".github/workflows/lean.yml", LEAN_WORKFLOW);
    write(root, "crates/demo/lean/lakefile.lean", LAKEFILE);
    write(
        root,
        "crates/demo/lean/lake-manifest.json",
        "{\"packages\":[]}",
    );
    write(root, "crates/demo/lean/generated/Demo/Funs.lean", FUNS);
    write(root, "crates/demo/lean/Proofs.lean", PROOFS);
    write(
        root,
        "crates/demo/lean/Orphan.lean",
        "theorem orphan : demo.admit 1#u8 = ok true := by rfl\n",
    );
    dir
}


#[test]
fn a_source_hash_pin_moves_with_the_code() {
    let dir = fixture();
    let row = |hash: &str| {
        format!(
            "[[obligation]]\nfunction = \"demo::admit\"\nkind = \"parity\"\nartifact = \"crates/demo/src/lib.rs::parity_admit\"\nstatus = \"proved\"\nsource_hash = \"{hash}\"\n"
        )
    };
    let (_, _, errors) = violations(dir.path(), &row("0")).unwrap();
    let now = errors[0]
        .rsplit("now ")
        .next()
        .unwrap()
        .trim_end_matches(')')
        .to_string();
    assert_eq!(
        violations(dir.path(), &row(&now)).unwrap().2,
        Vec::<String>::new()
    );
    // A comment is not code: the pin holds.
    write(
        dir.path(),
        "crates/demo/src/lib.rs",
        &lib().replace("    x < 10\n}", "    // bound\n    x < 10\n}"),
    );
    assert_eq!(
        violations(dir.path(), &row(&now)).unwrap().2,
        Vec::<String>::new()
    );
    // A code edit moves it.
    write(
        dir.path(),
        "crates/demo/src/lib.rs",
        &lib().replace("    x < 10\n}", "    x < 11\n}"),
    );
    let errors = violations(dir.path(), &row(&now)).unwrap().2;
    assert_eq!(errors.len(), 1, "{errors:#?}");
    assert!(
        errors[0].contains("changed since its source_hash"),
        "{errors:#?}"
    );
}


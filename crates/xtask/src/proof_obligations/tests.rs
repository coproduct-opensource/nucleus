#[test]
fn lean_statements_end_at_the_proof_and_mentions_need_two_segments() {
    let ts = lean::theorems(
        "@[simp] private theorem a (x : Nat) :\n    demo.admit x = ok true := by\n  simp\n-- theorem commented : demo.admit\ntheorem b : True := trivial\nlemma c {s : S := 1} : Gate.open s = 1 := rfl\n",
    );
    let names: Vec<_> = ts.iter().map(|t| t.name.as_str()).collect();
    assert_eq!(names, ["a", "b", "c"]);
    assert!(lean::mentions(&ts[0].statement, "demo.admit", &[]));
    assert!(!ts[0].statement.contains("simp"));
    assert!(!lean::mentions(&ts[1].statement, "demo.admit", &[]));
    assert!(lean::mentions(&ts[2].statement, "demo.Gate.open", &[]));
    // A bare last segment is a coincidence, not a mention ...
    assert!(!lean::mentions(
        "(h : admit x = ok true)",
        "demo.admit",
        &[]
    ));
    assert!(!lean::mentions("demo.admitted x", "demo.admit", &[]));
    // ... unless the file opens the namespace that makes it the constant.
    let scopes =
        lean::scopes("open Aeneas demo (Gate)\n-- open nope\nnamespace Proofs\nopen other in\n");
    assert_eq!(scopes, ["Aeneas", "demo", "Proofs", "other"]);
    assert!(lean::mentions(
        "(h : admit x = ok true)",
        "demo.admit",
        &scopes
    ));
    assert!(!lean::mentions(
        "(h : admit x = ok true)",
        "elsewhere.admit",
        &scopes
    ));
}

